def test_launch_options_headless(make_config):
    config = make_config(headless=True, window_size=(1024, 768))
    options = BrowserSession(config).launch_options()

    assert options["headless"] is True
    assert options["args"][:2] == ["--no-sandbox", "--disable-dev-shm-usage"]
    assert "--start-maximized" not in options["args"]
    assert options["viewport"] == {"width": 1024, "height": 768}
    assert options["user_data_dir"] == str(config.user_data_dir)
    assert "channel" not in options


def test_launch_options_headful_uses_the_real_window(make_config):
    config = make_config(headless=False, browser_channel="chrome",
                         browser_args=["--lang=en-GB"])
    options = BrowserSession(config).launch_options()

    assert options["headless"] is False
    assert "--start-maximized" in options["args"]
    assert options["viewport"] is None, "a maximised window must decide the viewport"
    assert "--lang=en-GB" in options["args"]
    assert options["channel"] == "chrome"


def test_sniffers_javascript_is_a_single_idempotent_iife():
    source = snapshot_js()

    assert source.lstrip().startswith("/*")
    assert source.rstrip().endswith(")()")
    assert "shadowRoot" in source and "iframe" in source
    assert "__webpilotInstalled" in source, "the error collector must install once"



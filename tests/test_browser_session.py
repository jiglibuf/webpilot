def test_raw_text_and_raw_html_are_bounded_and_for_extraction_only(browser_session, fixture_site):
    browser_session.goto(fixture_site)
    html = browser_session.raw_html()
    text = browser_session.raw_text()

    assert html.lower().startswith("<!doctype html")
    assert "Workspace gear" in text
    assert len(browser_session.raw_html(max_chars=200)) == 200
    assert len(browser_session.raw_text(max_chars=40)) == 40
    docstring = BrowserSession.raw_html.__doc__ or ""
    assert "Extractor" in docstring, "the raw accessors must warn the main loop off"


def test_screenshot_writes_into_the_configured_directory(browser_session, config, fixture_site):
    browser_session.goto(fixture_site)
    path = browser_session.screenshot("unit-test")

    assert Path(path).exists()
    assert Path(path).parent == Path(config.screenshot_dir)
    assert Path(path).stat().st_size > 0
    assert browser_session.last_model is None or browser_session.last_model.screenshot_path == path



def test_sniffer_finds_the_search_box(browser_session, fixture_site):
    browser_session.goto(f"{fixture_site}/search")
    model = browser_session.snapshot(budget_tokens=1200)

    box = element_named(model, "Search products", role="textbox")
    assert box is not None, [el.line() for el in model.elements]
    assert box.tag == "input"
    assert box.placeholder == "Search products"
    assert box.in_viewport is True
    assert box.id > 0
    assert model.generation >= 1
    assert model.html_chars > 500, "the sniffer reports how much html it did NOT send"
    # the page block we would send is a tiny fraction of the html we looked at
    from webpilot.browser.snapshot import render_page_model

    assert count_tokens(render_page_model(model, budget_tokens=1200)) < model.html_chars / 4


def test_submitting_a_search_updates_what_the_sniffer_sees(browser_session, fixture_site):
    browser_session.goto(f"{fixture_site}/search")
    model = browser_session.snapshot(budget_tokens=1200)
    box = element_named(model, "Search products", role="textbox")

    field = browser_session.page.locator(selector_for(box.id)).first
    field.press_sequentially("desk", delay=0)
    field.press("Enter")
    browser_session.page.wait_for_load_state("load")

    after = browser_session.snapshot(budget_tokens=1200)
    assert "q=desk" in after.url
    assert "Results for desk" in after.text
    assert element_named(after, "Standing Desk") is not None
    assert "Monitor Arm" not in after.text, "search results should be filtered"


def test_generation_advances_and_delta_sees_the_changes(browser_session, fixture_site):
    browser_session.goto(f"{fixture_site}/search")
    first = browser_session.snapshot(budget_tokens=1200)
    second = browser_session.snapshot(budget_tokens=1200, mode="delta")

    assert second.generation == first.generation + 1
    assert second.url == first.url
    assert len(second.elements) == len(first.elements)

    browser_session.goto(f"{fixture_site}/cart")
    third = browser_session.snapshot(budget_tokens=1200, mode="delta")
    # a navigation must not be rendered as a delta of the previous page
    assert third.url.endswith("/cart")
    assert third.url != second.url
    assert third.generation == second.generation + 1
    assert "Your cart is empty" in third.text


def test_snapshotting_twice_reuses_the_ids(browser_session, fixture_site):
    browser_session.goto(fixture_site)
    first = browser_session.snapshot(budget_tokens=1200)
    second = browser_session.snapshot(budget_tokens=1200)

    assert [(el.id, el.role, el.name) for el in first.elements] == \
        [(el.id, el.role, el.name) for el in second.elements]
    assert second.page_hash() == first.page_hash(), "the sniffer must be idempotent"


def test_ids_are_never_recycled_after_a_navigation(browser_session, fixture_site):
    """A stale id must stay unresolvable - otherwise a click could hit a stranger."""
    browser_session.goto(fixture_site)
    first = browser_session.snapshot(budget_tokens=1200)

    browser_session.goto(f"{fixture_site}/cart")
    second = browser_session.snapshot(budget_tokens=1200)

    assert min(el.id for el in second.elements) > max(el.id for el in first.elements)
    assert not ({el.id for el in first.elements} & {el.id for el in second.elements})


def test_shadow_dom_elements_are_found(browser_session, fixture_site):
    browser_session.goto(f"{fixture_site}/shadow")
    model = browser_session.snapshot(budget_tokens=1500)

    shadow_button = element_named(model, "Shadow action", role="button")
    assert shadow_button is not None, [el.line() for el in model.elements]
    assert shadow_button.frame == 0
    assert "Inside the shadow root" in model.text


def test_iframe_elements_get_their_own_frame_index(browser_session, fixture_site):
    browser_session.goto(f"{fixture_site}/iframe")
    model = browser_session.snapshot(budget_tokens=2000)

    assert len(model.frames) >= 2
    assert model.frames[1].endswith("/frame")
    note = element_named(model, "Note", role="textbox")
    assert note is not None, [el.line() for el in model.elements]
    assert note.frame == 1
    save = element_named(model, "Save note", role="submit")
    assert save is not None and save.frame == 1
    # main-frame and frame elements are both present, each with its own index
    assert {el.frame for el in model.elements} == {0, 1}


def test_native_dialogs_are_recorded_and_never_hang(browser_session, fixture_site):
    browser_session.goto(f"{fixture_site}/account")
    model = browser_session.snapshot(budget_tokens=1200)
    button = element_named(model, "Order history", role="button")
    assert button is not None

    browser_session.page.locator(selector_for(button.id)).first.click()

    assert browser_session.pending_dialogs, "the dialog handler must record the text"
    seen = browser_session.snapshot(budget_tokens=1200)
    assert any("Order history is empty" in dialog for dialog in seen.dialogs)
    assert browser_session.pending_dialogs == [], "dialogs are reported once"


def test_console_errors_are_collected_once(browser_session, fixture_site):
    browser_session.goto(f"{fixture_site}/errors")
    browser_session.snapshot(budget_tokens=800)
    browser_session.page.wait_for_timeout(400)
    model = browser_session.snapshot(budget_tokens=800)

    assert any("boom from the page" in error for error in model.errors), model.errors



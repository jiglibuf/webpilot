"""BrowserSession tests: launch, observation, dialogs and tabs.

They run headless against the bundled local store (``fixture_site``) - no
network, no API keys.  The session is addressed the way the agent addresses it:
element ids come from a snapshot, and the CSS that resolves an id is generated by
``selector_for`` (never a hand-written selector).
"""

from __future__ import annotations

from pathlib import Path

import pytest

from webpilot.browser.actions import selector_for
from webpilot.browser.session import BrowserSession, snapshot_js
from webpilot.tokenizer import count_tokens


def element_named(model, name: str, role: str | None = None):
    for element in model.elements:
        if name.lower() in element.name.lower() and (role is None or element.role == role):
            return element
    return None



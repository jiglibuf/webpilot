def test_tabs_open_switch_and_close(browser_session, fixture_site):
    browser_session.new_page(f"{fixture_site}/cart")

    assert len(browser_session.pages) == 2
    infos = browser_session.tab_infos()
    assert [info.index for info in infos] == [0, 1]
    assert infos[1].active is True and infos[1].url.endswith("/cart")

    browser_session.switch(0)
    assert browser_session.tab_infos()[0].active is True
    assert browser_session.page.url.rstrip("/") == fixture_site.rstrip("/")

    browser_session.close_page(1)
    assert len(browser_session.pages) == 1


def test_stop_is_idempotent_and_snapshot_afterwards_is_refused(browser_session, fixture_site):
    browser_session.stop()
    browser_session.stop()

    from webpilot.errors import BrowserError

    with pytest.raises(BrowserError):
        browser_session.snapshot(budget_tokens=400)
